import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from mo2_profile import parse_modlist
from report_html import render_report


class MO2Tests(unittest.TestCase):
    def test_real_format_markers_reversed_priority_and_source(self):
        raw = b'\xef\xbb\xbf# This file was automatically generated by Mod Organizer.\r\n+Patch\r\n-Disabled\r\n*DLC\r\n+Base\r\n-Group_separator\r\n'
        result = parse_modlist(raw)
        self.assertEqual(['Group_separator','Base','DLC','Disabled','Patch'],[e['name'] for e in result['mods']])
        self.assertEqual(['Base','Patch'],result['enabled_regular_names_low_to_high'])
        self.assertEqual([False,True,True,False,True],[e['enabled'] for e in result['mods']])
        self.assertEqual(['separator','regular','foreign','regular','regular'],[e['kind'] for e in result['mods']])
        self.assertEqual(hashlib.sha256(raw).hexdigest(), result['source_sha256'])
        self.assertFalse(result['manager_state_verified'])

    def test_overwrite_never_treated_as_regular(self):
        result=parse_modlist(b'+Overwrite\n+Regular\n')
        self.assertEqual(['Regular'],result['enabled_regular_names_low_to_high'])
        self.assertEqual('overwrite-reference',result['mods'][1]['kind'])

    def test_utf8_comments_whitespace_and_empty_export(self):
        self.assertEqual('Caf\u00e9',parse_modlist('+Caf\u00e9\n'.encode())['mods'][0]['name'])
        self.assertEqual([],parse_modlist(b'# exported empty\r\n\n')['mods'])
        self.assertEqual('Mod',parse_modlist(b'+ Mod \r\n')['mods'][0]['name'])

    def test_malformed_and_duplicate_fail_closed(self):
        for raw in [b'LegacyUnmarked',b'+',b'+../Escape',b'+C:\\Escape',b'+A\n-a\n',b'+A\x00',b'\xff', b'+'+b'x'*4096]:
            with self.subTest(raw=raw[:25]),self.assertRaises(ValueError):parse_modlist(raw)

    def test_limits(self):
        for raw in [b'#'+b'x'*2_000_000, ''.join(f'+Mod{i}\n' for i in range(4097)).encode()]:
            with self.assertRaises(ValueError):parse_modlist(raw)

    def test_html_escaping_and_cli_no_mutation(self):
        raw=b'+<b>Named</b>\n'  # slash invalid, reject before any report
        with self.assertRaises(ValueError):parse_modlist(raw)
        raw=b'+<b>Named\n+Base\n'
        self.assertIn('&lt;b&gt;Named',render_report(parse_modlist(raw)))
        with tempfile.TemporaryDirectory() as directory:
            p=Path(directory)/'modlist.txt';p.write_bytes(raw)
            result=subprocess.run([sys.executable,'mo2_profile.py',str(p)],capture_output=True)
            self.assertEqual(0,result.returncode)
            self.assertEqual(parse_modlist(raw),json.loads(result.stdout))
            self.assertEqual(raw,p.read_bytes());self.assertEqual([p],list(Path(directory).iterdir()))
